using Sanduhr.Core;
using Xunit;

namespace Sanduhr.Tests;

/// <summary>The Launcher's safety property: an installed app's ID or an https link, and nothing a shell could run as a command.</summary>
public class LauncherTargetTests
{
    [Theory]
    [InlineData("Microsoft.WindowsCalculator_8wekyb3d8bbwe!App")]
    [InlineData("Chrome._crx_bhaoniopoeodhdjnfhgmfmkkgkfcblf")]
    [InlineData("MSEdge._crx_abcdefghijklmnopabcdefghijklmnop")]
    [InlineData("Spotify")]
    [InlineData("com.squirrel.slack.slack")]
    [InlineData("Microsoft.AutoGenerated.{AB12CD34-0000-1111-2222-333344445555}")]
    [InlineData("Brave-Browser")]
    public void RealAppIdsPass(string id) => Assert.True(LauncherTarget.Validate(LauncherKind.App, id).Ok);

    [Fact]
    public void AnAppIdAtTheLimitPassesAndOneOverDoesNot()
    {
        Assert.True(LauncherTarget.Validate(LauncherKind.App, new string('a', 256)).Ok);
        var over = LauncherTarget.Validate(LauncherKind.App, new string('a', 257));
        Assert.False(over.Ok);
        Assert.NotEmpty(over.Reason);
    }

    [Theory]
    [InlineData(null)]
    [InlineData("")]
    [InlineData(" ")]
    [InlineData(" Spotify")]
    [InlineData("Spotify ")]
    [InlineData("Spotify\n")]
    [InlineData("Some App")]                                   // a space
    [InlineData(@"C:\Windows\System32\cmd.exe")]               // a drive path
    [InlineData(@"\\server\share\tool.exe")]                   // a UNC path
    [InlineData(@"{1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}\cmd.exe")] // a known-folder path form
    [InlineData("C:/Windows/notepad.exe")]
    [InlineData("../../evil.exe")]
    [InlineData("/usr/bin/x")]
    [InlineData("notepad.exe /c calc")]                        // an argument
    [InlineData("cmd.exe&calc")]
    [InlineData("Spotify;calc")]
    [InlineData("Spotify|calc")]
    [InlineData("Spotify%TEMP%")]
    [InlineData("Spotify^")]
    [InlineData("\"Spotify\"")]                                // quotes
    [InlineData("Spot'ify")]
    [InlineData("Spot`ify")]
    [InlineData("shell:AppsFolder\\Spotify")]                  // a shell path, not an ID
    [InlineData("shell:::{26EE0668-A00A-44D7-9371-BEB064C98683}")]
    [InlineData("file:///C:/x")]
    [InlineData("javascript:alert(1)")]
    [InlineData("https://example.com")]
    [InlineData("ms-settings:")]
    [InlineData("...")]                                        // no letter or digit
    [InlineData("!!!")]
    public void HostileOrMalformedAppIdsAreRefusedWithAReason(string? id)
    {
        var check = LauncherTarget.Validate(LauncherKind.App, id);
        Assert.False(check.Ok);
        Assert.False(string.IsNullOrWhiteSpace(check.Reason));
    }

    [Theory]
    [InlineData("https://example.com")]
    [InlineData("https://example.com/")]
    [InlineData("https://dash.626labs.dev/projects?id=1#top")]
    [InlineData("HTTPS://Example.COM/Path")]
    [InlineData("https://sub.example.co.uk:8443/a/b?c=d&e=f")]
    [InlineData("https://127.0.0.1/")]
    [InlineData("https://localhost")]
    public void HttpsLinksPass(string link) => Assert.True(LauncherTarget.Validate(LauncherKind.Link, link).Ok);

    [Theory]
    [InlineData(null)]
    [InlineData("")]
    [InlineData("example.com")]
    [InlineData("www.example.com")]
    [InlineData("http://example.com")]                         // not https
    [InlineData("HTTP://example.com")]
    [InlineData("ftp://example.com")]
    [InlineData("file:///C:/Windows/System32/cmd.exe")]
    [InlineData("file://server/share/x.exe")]
    [InlineData("javascript:alert(1)")]
    [InlineData("JaVaScRiPt:alert(1)")]
    [InlineData("data:text/html,<script>alert(1)</script>")]
    [InlineData("vbscript:msgbox(1)")]
    [InlineData("ms-settings:")]
    [InlineData("shell:AppsFolder\\Spotify")]
    [InlineData("mailto:a@b.c")]
    [InlineData("about:blank")]
    [InlineData(@"C:\Windows\notepad.exe")]
    [InlineData(@"\\server\share")]
    [InlineData("//example.com/path")]
    [InlineData("https:/example.com")]                         // one slash
    [InlineData("https:example.com")]
    [InlineData(@"https:\\example.com")]
    [InlineData(@"https://example.com\x")]                     // a backslash
    [InlineData("https://")]                                   // no host
    [InlineData("https:///path")]
    [InlineData("https://user:pass@example.com")]              // a sign-in part
    [InlineData("https://user@example.com")]
    [InlineData(" https://example.com")]                       // whitespace around
    [InlineData("https://example.com ")]
    [InlineData("https://exa mple.com")]
    [InlineData("https://example.com/a b")]
    [InlineData("https://example.com/\n")]
    [InlineData("https://example.com/\"")]                     // quotes
    [InlineData("https://example.com/'x")]
    [InlineData("https://example.com\" calc")]                 // an argument smuggled after a quote
    public void NonHttpsOrMalformedLinksAreRefusedWithAReason(string? link)
    {
        var check = LauncherTarget.Validate(LauncherKind.Link, link);
        Assert.False(check.Ok);
        Assert.False(string.IsNullOrWhiteSpace(check.Reason));
    }

    [Fact]
    public void ALinkAtTheLimitPassesAndOneOverDoesNot()
    {
        string prefix = "https://example.com/";
        Assert.True(LauncherTarget.Validate(LauncherKind.Link, prefix + new string('a', 2048 - prefix.Length)).Ok);
        Assert.False(LauncherTarget.Validate(LauncherKind.Link, prefix + new string('a', 2049 - prefix.Length)).Ok);
    }

    [Fact]
    public void AnUnknownKindIsRefused() =>
        Assert.False(LauncherTarget.Validate((LauncherKind)99, "Spotify").Ok);

    [Fact]
    public void TheShellPathAndTheUrlAreBuiltOnlyFromValidTargets()
    {
        Assert.Equal(@"shell:AppsFolder\Spotify", LauncherTarget.AppShellPath("Spotify"));
        Assert.Null(LauncherTarget.AppShellPath(@"C:\x.exe"));
        Assert.Null(LauncherTarget.AppShellPath("a b"));
        Assert.Equal("https://example.com/a", LauncherTarget.LinkUrl("https://example.com/a"));
        Assert.Equal("https://example.com/", LauncherTarget.LinkUrl("HTTPS://EXAMPLE.com"));
        Assert.Null(LauncherTarget.LinkUrl("http://example.com"));
        Assert.Null(LauncherTarget.LinkUrl("javascript:alert(1)"));
    }

    [Fact]
    public void LinkHostDropsWww()
    {
        Assert.Equal("example.com", LauncherTarget.LinkHost("https://www.example.com/x"));
        Assert.Equal("dash.example.com", LauncherTarget.LinkHost("https://dash.example.com"));
        Assert.Equal("", LauncherTarget.LinkHost("http://example.com"));
    }

    [Fact]
    public void KindWordsRoundTrip()
    {
        foreach (var kind in new[] { LauncherKind.App, LauncherKind.Link })
            Assert.Equal(kind, LauncherTarget.ParseKind(LauncherTarget.Word(kind)));
        Assert.Null(LauncherTarget.ParseKind("exe"));
        Assert.Null(LauncherTarget.ParseKind("App"));
        Assert.Null(LauncherTarget.ParseKind(null));
    }
}
