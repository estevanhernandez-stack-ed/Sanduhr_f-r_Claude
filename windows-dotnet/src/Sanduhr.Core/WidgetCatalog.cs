namespace Sanduhr.Core;

/// <summary>One pack the catalog lists (FORMAT section 7): exactly the eight keys <c>build_catalog.py</c> writes.</summary>
public sealed record WidgetCatalogEntry(
    string Id,
    string Name,
    string Kind,
    string Version,
    string SanduhrMin,
    string Url,
    string Sha256,
    long Size);

/// <summary>A verified, parsed <c>catalog.json</c>. <see cref="GeneratedAtText"/> is the file's own string, kept for
/// the rollback marker so the comparison never depends on a round trip through a clock type.</summary>
public sealed record WidgetCatalogDocument(DateTimeOffset GeneratedAt, string GeneratedAtText, IReadOnlyList<WidgetCatalogEntry> Packs);

/// <summary>
/// The widget catalog client's pure half (FORMAT section 7, spec 2): the pinned keys, signature verification over the
/// exact downloaded bytes, the strict catalog parser, the rollback check, <c>sanduhr_min</c>, and the size and SHA-256
/// check on a downloaded zip. No disk, no network: the app's <c>WidgetCatalogService</c> fetches, this decides.
///
/// Client rules, in order, stopping at the first failure: (1) verify the signature against the embedded keys before
/// parsing anything, (2) reject a rollback by <c>generated_at</c>, (3) check <c>sanduhr_min</c>, then <c>size</c> and
/// <c>sha256</c> before opening the zip, (4) extract safely (<see cref="WidgetZip"/>), (5) re-validate locally
/// (<see cref="PackValidator"/>, strict), (6) install atomically (<see cref="WidgetStore"/>).
/// </summary>
public static partial class WidgetCatalog
{
