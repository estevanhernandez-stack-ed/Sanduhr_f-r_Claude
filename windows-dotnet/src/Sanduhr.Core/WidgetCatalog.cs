    [GeneratedRegex(@"[\x00-\x1f\x7f]", RegexOptions.CultureInvariant)]
    private static partial Regex CtrlRe();

    // ---- rule 1: the signature ----------------------------------------------------------------------------------------

    /// <summary>
    /// A signature file's 64 bytes, or null. The file is base64 (standard alphabet, padded) on one line; surrounding
    /// whitespace is stripped first. Anything else (another character, a second line, a length other than 64 decoded
    /// bytes) is not a signature.
    /// </summary>
    public static byte[]? DecodeSignature(ReadOnlySpan<byte> file)
    {
        if (file.Length == 0 || file.Length > MaxSignatureFileBytes)
            return null;
        foreach (byte b in file)
            if (b > 0x7e)
                return null;
        string text = Encoding.ASCII.GetString(file).Trim(' ', '\t', '\r', '\n');
        if (text.Length == 0)
            return null;
        foreach (char c in text)
        {
            bool ok = c is >= 'A' and <= 'Z' or >= 'a' and <= 'z' or >= '0' and <= '9' or '+' or '/' or '=';
            if (!ok)
                return null;
        }
        byte[] sig;
        try { sig = Convert.FromBase64String(text); }
        catch (FormatException) { return null; }
        return sig.Length == SignatureBytes ? sig : null;
    }

    /// <summary>Imports a pinned key. Null unless it is a DER SubjectPublicKeyInfo for a 256-bit NIST P-256 key with no
    /// trailing bytes.</summary>
    public static ECDsa? ImportKey(string spkiBase64)
    {
        byte[] der;
        try { der = Convert.FromBase64String(spkiBase64); }
        catch (FormatException) { return null; }
        var key = ECDsa.Create();
        try
        {
            key.ImportSubjectPublicKeyInfo(der, out int read);
            if (read != der.Length || key.KeySize != 256)
            {
                key.Dispose();
                return null;
            }
            var curve = key.ExportParameters(false).Curve;
            if (!curve.IsNamed || curve.Oid?.Value != P256Oid)
            {
                key.Dispose();
                return null;
            }
            return key;
        }
        catch (CryptographicException)
        {
            key.Dispose();
            return null;
        }
    }

    /// <summary>
    /// True when any of <paramref name="signatureFiles"/> (the raw <c>.sig</c> and <c>.sig2</c> bytes; a missing file
    /// is null) is a valid ECDSA P-256 / SHA-256 signature, IEEE P1363 form, over exactly <paramref name="catalog"/>,
    /// by any of <paramref name="pinnedKeys"/>. The keys are a parameter so tests sign with a throwaway key; the app
    /// passes <see cref="PinnedKeys"/>. Never throws.
    /// </summary>
    public static bool VerifySignature(byte[] catalog, IEnumerable<byte[]?> signatureFiles, IReadOnlyList<string> pinnedKeys)
    {
        if (catalog is null || signatureFiles is null || pinnedKeys is null || pinnedKeys.Count == 0)
            return false;
        var sigs = signatureFiles.Where(f => f is not null).Select(f => DecodeSignature(f)).Where(s => s is not null).ToList();
        if (sigs.Count == 0)
            return false;
        foreach (var spki in pinnedKeys)
        {
            using var key = ImportKey(spki);
            if (key is null)
                continue;
            foreach (var sig in sigs)
            {
                try
                {
                    if (key.VerifyData(catalog, sig!, HashAlgorithmName.SHA256, DSASignatureFormat.IeeeP1363FixedFieldConcatenation))
                        return true;
                }
                catch (CryptographicException)
                {
                    // Not this one.
                }
            }
        }
        return false;
    }

    // ---- after the signature: the strict parse ------------------------------------------------------------------------

    /// <summary>
    /// Parses a catalog whose signature already verified. Strict, as FORMAT 7 writes it: UTF-8 without a byte-order
    /// mark, no duplicate keys, exactly the documented keys, <c>schema_version</c> 1, <c>generated_at</c> as
    /// <c>YYYY-MM-DDTHH:MM:SSZ</c>, packs sorted by id with no id twice, and every pack's URL under this repository's
    /// releases, ending in <c>&lt;id&gt;-&lt;version&gt;.zip</c>. Null with a reason on anything else.
    /// </summary>
    public static WidgetCatalogDocument? Parse(byte[] bytes, out string error)
    {
        error = "";
        if (bytes is null || bytes.Length == 0)
        {
            error = "the catalog is empty";
            return null;
        }
        if (bytes.Length > MaxCatalogBytes)
        {
            error = "the catalog is larger than 1 MB";
            return null;
        }
        if (bytes.Length >= 3 && bytes[0] == 0xEF && bytes[1] == 0xBB && bytes[2] == 0xBF)
        {
            error = "the catalog starts with a byte-order mark";
            return null;
        }
        try
        {
            _ = new UTF8Encoding(false, true).GetString(bytes);
        }
        catch (DecoderFallbackException)
        {
            error = "the catalog is not UTF-8";
            return null;
        }
        if (!PackJson.TryParse(bytes, out var root, out var jsonError))
        {
            error = "the catalog is not valid JSON (" + jsonError + ")";
            return null;
        }
        if (root is not PackObject o)
        {
            error = "the catalog is not a JSON object";
            return null;
        }
        if (!SameKeys(o, CatalogKeys))
        {
            error = "the catalog's keys must be exactly " + string.Join(", ", CatalogKeys);
            return null;
        }
        if (o["schema_version"] is not PackNumber { IsInt: true, Value: 1 })
        {
            error = "the catalog's schema_version must be 1";
            return null;
        }
        if (o["generated_at"] is not string stamp || ParseStamp(stamp) is not { } generatedAt)
        {
            error = "the catalog's generated_at must be a UTC time written YYYY-MM-DDTHH:MM:SSZ";
            return null;
        }
        if (o["packs"] is not List<object?> list)
        {
            error = "the catalog's packs must be an array";
            return null;
        }
        if (list.Count > MaxPacks)
        {
            error = $"the catalog lists more than {MaxPacks} packs";
            return null;
        }
        var packs = new List<WidgetCatalogEntry>(list.Count);
        for (int i = 0; i < list.Count; i++)
        {
            var entry = ParseEntry(list[i], out var why);
            if (entry is null)
            {
                error = $"catalog pack {i}: {why}";
                return null;
            }
            if (packs.Count > 0 && string.CompareOrdinal(packs[^1].Id, entry.Id) >= 0)
            {
                error = $"catalog pack {i}: packs must be sorted by id, each id once ('{entry.Id}' after '{packs[^1].Id}')";
                return null;
            }
            packs.Add(entry);
        }
        return new WidgetCatalogDocument(generatedAt, stamp, packs);
    }

    private static WidgetCatalogEntry? ParseEntry(object? value, out string error)
    {
        error = "";
        if (value is not PackObject e)
        {
            error = "not a JSON object";
            return null;
        }
        if (!SameKeys(e, EntryKeys))
        {
            error = "keys must be exactly " + string.Join(", ", EntryKeys);
            return null;
        }
        foreach (var k in EntryKeys)
        {
            if (k == "size") continue;
            if (e[k] is not string s)
            {
                error = $"{k} must be a string";
                return null;
            }
            if (CtrlRe().IsMatch(s))
            {
                error = $"{k} has a control character";
                return null;
            }
        }
        string id = (string)e["id"]!, name = (string)e["name"]!, kind = (string)e["kind"]!, version = (string)e["version"]!;
        string min = (string)e["sanduhr_min"]!, url = (string)e["url"]!, sha = (string)e["sha256"]!;
        if (id.Length < 3 || id.Length > 40 || !IdRe().IsMatch(id))
        {
            error = "id must be lowercase kebab-case, 3 to 40 characters";
            return null;
        }
        if (name.Length < 1 || name.Length > 40)
        {
            error = "name must be 1 to 40 characters";
            return null;
        }
        if (!PackValidator.Kinds.Contains(kind))
        {
            error = "kind must be one of " + string.Join(", ", PackValidator.Kinds);
            return null;
        }
        if (!SemverRe().IsMatch(version))
        {
            error = "version must be MAJOR.MINOR.PATCH";
            return null;
        }
        if (!SemverRe().IsMatch(min))
        {
            error = "sanduhr_min must be MAJOR.MINOR.PATCH";
            return null;
        }
        if (!Sha256Re().IsMatch(sha))
        {
            error = "sha256 must be 64 lowercase hex characters";
            return null;
        }
        if (e["size"] is not PackNumber { IsInt: true } sizeNumber || !sizeNumber.IsFinite
            || sizeNumber.Value < 1 || sizeNumber.Value > MaxZipBytes)
        {
            error = $"size must be an integer from 1 to {MaxZipBytes}";
            return null;
        }
        if (!IsPackUrl(url, id, version))
        {
            error = $"url must be {DownloadPrefix}<tag>/{id}-{version}.zip";
            return null;
        }
        return new WidgetCatalogEntry(id, name, kind, version, min, url, sha, (long)sizeNumber.Value);
    }

    /// <summary>A pack URL: this repository's release download, one tag segment, then exactly <c>id-version.zip</c>.</summary>
    public static bool IsPackUrl(string url, string id, string version)
    {
        if (!url.StartsWith(DownloadPrefix, StringComparison.Ordinal))
            return false;
        var rest = url[DownloadPrefix.Length..];
        int slash = rest.IndexOf('/');
        if (slash <= 0)
            return false;
        string tag = rest[..slash], file = rest[(slash + 1)..];
        return TagRe().IsMatch(tag) && tag != "." && tag != ".." && file == $"{id}-{version}.zip";
    }

    /// <summary>True for an https URL whose host may serve the catalog or a pack (a redirect target included).</summary>
    public static bool IsAllowedUrl(Uri? uri) =>
        uri is not null && uri.IsAbsoluteUri && uri.Scheme == Uri.UriSchemeHttps && uri.IsDefaultPort
        && string.IsNullOrEmpty(uri.UserInfo)
        && AllowedHosts.Contains(uri.Host.ToLowerInvariant());

    private static bool SameKeys(PackObject o, string[] keys) =>
        o.Count == keys.Length && keys.All(o.Has);

    /// <summary><c>YYYY-MM-DDTHH:MM:SSZ</c> as UTC, or null.</summary>
    public static DateTimeOffset? ParseStamp(string? stamp)
    {
        if (stamp is null || !StampRe().IsMatch(stamp))
            return null;
        return DateTimeOffset.TryParseExact(stamp, "yyyy-MM-dd'T'HH:mm:ss'Z'", CultureInfo.InvariantCulture,
            DateTimeStyles.AssumeUniversal | DateTimeStyles.AdjustToUniversal, out var t)
            ? t
            : null;
    }

    // ---- rule 2: rollback ---------------------------------------------------------------------------------------------

    /// <summary>True when <paramref name="generatedAt"/> is older than the newest catalog already seen. The same
    /// catalog again is not a rollback.</summary>
    public static bool IsRollback(DateTimeOffset generatedAt, DateTimeOffset? newestSeen) =>
        newestSeen is { } seen && generatedAt < seen;

    // ---- rule 3: sanduhr_min, size, sha256 ----------------------------------------------------------------------------

    /// <summary>True when the running Sanduhr (major.minor.build) is at least <paramref name="sanduhrMin"/>. A minimum
    /// that is not MAJOR.MINOR.PATCH is never met.</summary>
    public static bool MeetsMinimum(string sanduhrMin, Version running)
    {
        if (running is null || !SemverRe().IsMatch(sanduhrMin ?? ""))
            return false;
        var parts = sanduhrMin!.Split('.');
        if (!int.TryParse(parts[0], NumberStyles.None, CultureInfo.InvariantCulture, out int major)
            || !int.TryParse(parts[1], NumberStyles.None, CultureInfo.InvariantCulture, out int minor)
            || !int.TryParse(parts[2], NumberStyles.None, CultureInfo.InvariantCulture, out int patch))
            return false;
        var have = (running.Major, running.Minor, Math.Max(running.Build, 0));
        return have.CompareTo((major, minor, patch)) >= 0;
    }

    /// <summary>Checks a downloaded zip against its catalog entry: the exact size, then the SHA-256. Null when both
    /// match, otherwise the reason. Run before the zip is opened.</summary>
    public static string? CheckDownload(WidgetCatalogEntry entry, byte[] zip)
    {
        if (zip is null || zip.LongLength != entry.Size)
            return $"the download is {zip?.LongLength ?? 0} bytes, the catalog says {entry.Size}";
        string hex = Convert.ToHexStringLower(SHA256.HashData(zip));
        return CryptographicOperations.FixedTimeEquals(Encoding.ASCII.GetBytes(hex), Encoding.ASCII.GetBytes(entry.Sha256))
            ? null
            : "the download's SHA-256 does not match the catalog";
    }

    /// <summary>Compares two MAJOR.MINOR.PATCH versions; a malformed one sorts first.</summary>
    public static int CompareVersions(string? a, string? b)
    {
        static (int, int, int) Parts(string? v)
        {
            if (v is null || !SemverRe().IsMatch(v)) return (-1, -1, -1);
            var p = v.Split('.');
            int P(string s) => int.TryParse(s, NumberStyles.None, CultureInfo.InvariantCulture, out int n) ? n : int.MaxValue;
            return (P(p[0]), P(p[1]), P(p[2]));
        }
        return Parts(a).CompareTo(Parts(b));
    }
}
